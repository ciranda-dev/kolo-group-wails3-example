/**
 * The first language of the list that we have, English when there is none.
 * @param {readonly string[]} [tags] such as navigator.languages
 */
export function pickLanguage(tags = []) {
  for (const tag of tags) {
    const lang = String(tag).toLowerCase().split(/[-_]/)[0]
    if (Object.hasOwn(strings, lang)) {
      return lang
    }
  }
  return 'en'
}

/** The language of this browser or webview. */
export const browserLanguage = () =>
  pickLanguage(typeof navigator === 'undefined' ? [] : (navigator.languages ?? [navigator.language]))

/**
 * The string for key in lang, with {n} replaced.
 * @param {string} lang
 * @param {string} key
 * @param {number | string} [n]
 */
export function t(lang, key, n) {
  const text = (strings[lang] ?? strings.en)[key] ?? strings.en[key] ?? key
  return n === undefined ? text : text.replaceAll('{n}', String(n)).replaceAll('{name}', String(n))
}

/** The key of a count: ".one" when the language has it for n, ".other" otherwise. */
export function countKey(lang, key, n) {
  const form = n === 1 ? 'one' : 'other'
  return Object.hasOwn(strings[lang] ?? strings.en, `${key}.${form}`) ? `${key}.${form}` : `${key}.other`
}
